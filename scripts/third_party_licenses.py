"""Generate or verify the lockfile-wide third-party notice without extra packages."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "THIRD_PARTY_LICENSES.txt"
DOCUMENT_NAME = re.compile(r"licen[sc]e|copying|copyright|notice|authors", re.I)
COPYRIGHT = re.compile(
    r"^\s*(?:[/#*!<>-]+\s*)?(?:SPDX-FileCopyrightText:\s*)?"
    r"(?:Copyright\s+(?:\([cC]\)\s*|©\s*)?(?:\[?[12][0-9]{3}|[A-Z][a-zA-Z.,-]+\b)|©\s*[12][0-9]{3}|\([cC]\)\s*[12][0-9]{3}\b)"
)


def digest(data):
    """Return a stable content identity for source or generated bytes."""
    return hashlib.sha256(data).hexdigest()


def identity(package):
    """Keep versions and registries distinct, including duplicate crate names."""
    return package["name"], package["version"], package.get("source")


def copyright_lines(text):
    """Extract actual statements, excluding unfilled license-template examples."""
    result = set()
    for line in text.splitlines():
        if (
            COPYRIGHT.search(line) or line.strip().startswith("Copyrights in ")
        ) and not any(
            placeholder in line.lower()
            for placeholder in (
                "[yyyy]",
                "{yyyy}",
                "<year>",
                "[year]",
                "copyright notice",
                "copyright holder",
                "copyright license",
            )
        ):
            result.add(line.strip().removeprefix("//").removeprefix("*").strip())
    return result


def source_documents(package):
    """Preserve packaged license/notice files, including embedded dependencies."""
    root = Path(package["manifest_path"]).parent
    documents = []
    for path in sorted(root.rglob("*")):
        if not path.is_file() or not DOCUMENT_NAME.search(path.name):
            continue
        if path.suffix.lower() in (".rs", ".c", ".h", ".html", ".json"):
            continue
        text = path.read_text(encoding="utf-8")
        label = str(path.relative_to(root))
        # r-efi places three alternative grants in AUTHORS. Retain the chosen
        # MIT grant and all holders/contributors without electing the LGPL grant.
        if package["name"] == "r-efi" and label == "AUTHORS":
            text = (
                "AUTHORS-MIT:"
                + text.split("AUTHORS-MIT:", 1)[1].split("AUTHORS-ASL:", 1)[0]
            )
            text += (
                "COPYRIGHT:"
                + path.read_text(encoding="utf-8").split("COPYRIGHT:", 1)[1]
            )
            label += " (MIT grant, copyright and authors)"
        if text.strip():
            documents.append((label, text))
    return documents


def source_copyright(package):
    """Find copyright headers when a crate's license file omits its holders."""
    root = Path(package["manifest_path"]).parent
    statements = set()
    for path in sorted(root.rglob("*")):
        if path.is_file() and path.suffix in (".rs", ".c", ".h", ".cpp", ".cc"):
            statements.update(copyright_lines(path.read_text(encoding="utf-8")))
    return statements


def render(metadata, lock_bytes, selections, supplements):
    """Require complete lockfile coverage before emitting any notice text."""
    locked = {
        identity(p)
        for p in tomllib.loads(lock_bytes.decode())["package"]
        if p.get("source")
    }
    packages = {identity(p): p for p in metadata["packages"] if p.get("source")}
    if packages.keys() != locked:
        raise ValueError(
            f"metadata/lockfile mismatch: missing={locked - packages.keys()}, extra={packages.keys() - locked}"
        )

    blocks = {}
    entries = []
    supplemented_names = {name for name, _version in supplements}
    for key, package in sorted(packages.items()):
        name, version, _source = key
        # A version bump must not drop a previously required source notice or
        # attribution supplement merely because its old version no longer matches.
        if name in supplemented_names and (name, version) not in supplements:
            raise ValueError(f"review source supplements for {name} {version}")
        expression = package.get("license")
        if expression not in selections:
            raise ValueError(
                f"review the new license expression for {name} {version}: {expression!r}"
            )
        selected = selections[expression]
        if name == "r-efi" and selected not in ("MIT", "Apache-2.0"):
            raise ValueError("r-efi must use its MIT or Apache-2.0 grant")
        documents = source_documents(package)
        extra = supplements.get((name, version), {})
        if extra and extra.get("declared_license", expression) != expression:
            raise ValueError(f"review the upstream supplement for {name} {version}")
        for document in extra.get("files", []):
            path = ROOT / "licenses/upstream" / document["filename"]
            raw = path.read_bytes()
            if digest(raw) != document["sha256"]:
                raise ValueError(f"upstream license checksum changed: {path}")
            documents.append((document["upstream_url"], raw.decode("utf-8")))
        if not documents:
            raise ValueError(f"no upstream license documents for {name} {version}")
        holders = set().union(*(copyright_lines(text) for _label, text in documents))
        if not holders:
            holders = source_copyright(package)
        attribution = package.get("authors")
        if extra.get("attribution"):
            attribution = [extra["attribution"]["value"]]
            evidence = extra["attribution"]
            if "crate_file" in evidence:
                path = Path(package["manifest_path"]).parent / evidence["crate_file"]
                if digest(path.read_bytes()) != evidence["sha256"]:
                    raise ValueError(
                        f"attribution evidence changed for {name} {version}"
                    )
        if not holders and not attribution:
            raise ValueError(
                f"no upstream copyright or attribution for {name} {version}"
            )
        source = (
            f"https://crates.io/crates/{name}/{version}"
            if _source == "registry+https://github.com/rust-lang/crates.io-index"
            else _source
        )
        lines = [
            f"COMPONENT: {name} {version}",
            f"Source: {source}",
            f"Declared license: {expression}",
            f"Selected license: {selected}",
        ]
        for license in extra.get("additional_licenses", []):
            lines.append(f"Bundled code: {license['license']}: {license['scope']}")
        if holders:
            lines.append("Copyright statements (upstream):")
            lines.extend(f"  {holder}" for holder in sorted(holders))
        if attribution:
            lines.append("Upstream attribution: " + "; ".join(attribution))
        if not holders:
            lines.append(
                "Upstream supplies no separate copyright statement; author/project attribution is retained above."
            )
        lines.append("License and notice texts:")
        for label, text in documents:
            # Equal text shares one block, but each component retains its own
            # source label. No workstation paths or generated timestamps escape.
            normalized = (
                "\n".join(line.rstrip() for line in text.splitlines()).strip() + "\n"
            )
            block_id = digest(normalized.encode())
            blocks[block_id] = normalized
            lines.append(f"  TEXT-{block_id}: {label}")
        entries.append("\n".join(lines))

    header = [
        "APF THIRD-PARTY LICENSES AND COPYRIGHT NOTICES",
        "============================================",
        "",
        "Generated by scripts/third_party_licenses.py from Cargo.lock and upstream crate sources.",
        f"Cargo.lock SHA-256: {digest(lock_bytes)}",
        f"External crate versions: {len(entries)}",
        "",
        "This inventory includes every registry/git dependency in Cargo.lock, including optional,",
        "build, development and platform-specific dependencies. It is broader than any one binary.",
        "Each component records its declared expression and APF's selected grant. Required AND",
        "terms are retained. Additional licenses and notices for bundled code remain in the texts.",
        "",
        "APF selects MIT for r-efi. Its upstream MIT OR Apache-2.0 OR LGPL-2.1-or-later expression",
        "offers alternatives; APF does not elect LGPL. The MIT grant and copyrights appear below.",
        "",
        "Copyright statements are copied from upstream. Where upstream supplies no separate",
        "statement, its author/project attribution is identified without inventing copyright.",
        "Upstream license texts can include unfilled examples or alternative grants; these are",
        "preserved as published and do not change the selected license stated for each component.",
        "Distribute this file alongside APF binaries and retain it in APF container images.",
    ]
    output = "\n".join(header) + "\n\n" + "\n\n".join(entries) + "\n\n"
    output += "FULL UPSTREAM LICENSE AND NOTICE TEXTS\n=====================================\n\n"
    output += "\n".join(
        f"TEXT-{key}\n{'-' * 72}\n{value}" for key, value in sorted(blocks.items())
    )
    return output


def main():
    """Generate atomically, or fail a check if the checked-in notice is stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--offline", action="store_true", help="use already fetched Cargo sources"
    )
    args = parser.parse_args()
    command = [
        "cargo",
        "metadata",
        "--locked",
        "--all-features",
        "--format-version",
        "1",
    ]
    if args.offline:
        command.append("--offline")
    metadata = json.loads(subprocess.check_output(command, cwd=ROOT))
    selections = json.loads((ROOT / "licenses/selections.json").read_text())
    supplements = json.loads((ROOT / "licenses/upstream/provenance.json").read_text())[
        "packages"
    ]
    supplements += json.loads((ROOT / "licenses/attribution.json").read_text())
    by_package = {(p["name"], p["version"]): p for p in supplements}
    result = render(
        metadata, (ROOT / "Cargo.lock").read_bytes(), selections, by_package
    )
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != result:
            raise ValueError(
                "THIRD_PARTY_LICENSES.txt is stale; run scripts/third_party_licenses.py"
            )
        print(
            "THIRD_PARTY_LICENSES.txt matches every external Cargo.lock entry and its source notices."
        )
    else:
        temporary = OUTPUT.with_suffix(".txt.tmp")
        temporary.write_text(result, encoding="utf-8")
        temporary.replace(OUTPUT)
        print(f"Wrote {OUTPUT.name}")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as error:
        print(f"third-party notices: {error}", file=sys.stderr)
        sys.exit(1)
